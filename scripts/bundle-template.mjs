#!/usr/bin/env node
/**
 * Bundles `workspace-template/` into `src/lib/github/template.generated.ts`, so the deployed app can
 * create any user's workspace repository from its own files (users' tokens cannot read the app repo).
 * Run after editing the template: `npm run template` (a test fails when the bundle is out of date).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "workspace-template");
const out = path.join(root, "src/lib/github/template.generated.ts");

function walk(d) {
  return fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => {
    const full = path.join(d, e.name);
    return e.isDirectory() ? walk(full) : [full];
  });
}

const files = walk(dir)
  .map((f) => ({ path: path.relative(dir, f).split(path.sep).join("/"), content: fs.readFileSync(f, "utf-8") }))
  .sort((a, b) => a.path.localeCompare(b.path));

const body = `// Generated by scripts/bundle-template.mjs from workspace-template/ — do not edit by hand.
export const TEMPLATE_FILES: { path: string; content: string }[] = ${JSON.stringify(files, null, 2)};
`;
const check = process.argv.includes("--check");
if (check) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, "utf-8") : "";
  if (current !== body) {
    console.error("template.generated.ts is out of date: run `npm run template`");
    process.exit(1);
  }
} else {
  fs.writeFileSync(out, body);
  console.log(`bundled ${files.length} template files`);
}
