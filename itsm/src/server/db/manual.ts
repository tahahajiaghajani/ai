// The database scripts for running by hand, built from the very steps the app runs (./migrate.ts): `npm run schema`
// writes them (scripts/gen-schema.mts) and tests/schema-manual.test.ts checks they stay in sync and work.
//   supabase/schema.sql             everything, in order (psql or any client without a size limit)
//   supabase/manual/NN-of-MM.sql    the same in parts small enough for the Supabase SQL Editor
//   supabase/migrations/<id>.sql    one file per migration
//   src/server/db/schema-fingerprint.generated.ts   what this build expects (./schema-check.ts)
import { MIGRATIONS } from "./migrations";
import { engineChunks } from "../engine/ddl";
import { APP_NAME } from "@shared/constants";

/**
 * Bytes per SQL Editor part. Supabase Studio refuses a query over ≈ 0.98 MB ("Query is too large to be run via the SQL
 * Editor", apps/studio/data/sql/execute-sql-mutation.ts); a part stays well under it and runs in seconds.
 */
export const MANUAL_PART_BYTES = 400_000;
export const SQL_EDITOR_LIMIT_BYTES = Math.floor(0.98 * 1024 * 1024);

const INIT = "create table if not exists sm_migrations (id text primary key, applied_at timestamptz not null default now());";
const fa = (n: number) => String(n).replace(/\d/g, (d) => "۰۱۲۳۴۵۶۷۸۹"[Number(d)]);
const pad = (n: number) => String(n).padStart(2, "0");
const RULE = "-- ---------------------------------------------------------------------------";

function wrap(id: string, title: string, sql: string) {
  return `${RULE}\n-- ${id} — ${title}\n${RULE}\n${sql.trim()}\n\ninsert into sm_migrations (id) values ('${id}') on conflict (id) do nothing;\n`;
}

export interface ManualSchema {
  /** repository-relative path → content */
  files: Record<string, string>;
  /** the steps in order, as run by hand */
  steps: { id: string; sql: string }[];
  parts: number;
  largestPart: number;
}

export function manualSchema(): ManualSchema {
  const { hash, chunks } = engineChunks();
  // the app's order: every migration, the record engine's DDL in its chunks in place of 0006 (each chunk records itself
  // and the last one records 0006 and the DDL version — exactly as when the app runs it)
  const steps: { id: string; sql: string }[] = [];
  for (const m of MIGRATIONS) {
    if (m.id === "0006_engine_tables") {
      for (const c of chunks)
        steps.push({ id: `0006_engine_tables:${c.index + 1}/${c.total}`, sql: `${RULE}\n-- 0006_engine_tables — ${m.title} — بخش ${fa(c.index + 1)} از ${fa(c.total)}\n${RULE}\n${c.sql}\n` });
    } else steps.push({ id: m.id, sql: wrap(m.id, m.title, m.sql) });
  }

  // parts of at most MANUAL_PART_BYTES; a step is never split
  const groups: { first: string; last: string; sql: string[]; bytes: number }[] = [];
  for (const s of steps) {
    const bytes = Buffer.byteLength(s.sql) + 1;
    const cur = groups[groups.length - 1];
    if (!cur || cur.bytes + bytes > MANUAL_PART_BYTES) groups.push({ first: s.id, last: s.id, sql: [s.sql], bytes });
    else {
      cur.sql.push(s.sql);
      cur.last = s.id;
      cur.bytes += bytes;
    }
  }

  const files: Record<string, string> = {};
  files["supabase/schema.sql"] = `-- ============================================================================
-- «${APP_NAME}» — پایگاه دادهٔ کامل برای Supabase (PostgreSQL 15+)
-- برای psql یا هر ابزاری که اندازهٔ کوئری را محدود نمی‌کند. SQL Editor خود Supabase کوئری بزرگ‌تر از حدود ۱ مگابایت را
-- نمی‌پذیرد: به‌جای این فایل بخش‌های پوشهٔ supabase/manual را به‌ترتیب اجرا کنید (docs/SETUP_FA.md بخش ۱-۵).
-- معمولاً هیچ‌کدام لازم نیست: ساخت Vercel، scripts/migrate-db.mts یا خود برنامه همین مرحله‌ها را اجرا می‌کند.
-- اجرای دوباره بی‌خطر است: همهٔ دستورها idempotent هستند و هر مرحله خودش را ثبت می‌کند.
-- این فایل خودکار ساخته می‌شود: npm run schema
-- ============================================================================

${INIT}

${steps.map((s) => s.sql).join("\n")}`;
  let largestPart = 0;
  groups.forEach((g, i) => {
    const text = `-- «${APP_NAME}» — پایگاه داده برای Supabase SQL Editor: بخش ${fa(i + 1)} از ${fa(groups.length)} (${g.first} … ${g.last})
-- بخش‌ها را به‌ترتیب، هر کدام یک بار، در یک snippet تازه بچسبانید و Run بزنید (docs/SETUP_FA.md بخش ۱-۵).
-- اجرای دوباره بی‌خطر است. خودکار ساخته می‌شود: npm run schema
${INIT}

${g.sql.join("\n")}`;
    largestPart = Math.max(largestPart, Buffer.byteLength(text));
    files[`supabase/manual/${pad(i + 1)}-of-${pad(groups.length)}.sql`] = text;
  });
  for (const m of MIGRATIONS) {
    const body = m.id === "0006_engine_tables" ? steps.filter((s) => s.id.startsWith("0006_engine_tables")).map((s) => s.sql).join("\n") : wrap(m.id, m.title, m.sql);
    files[`supabase/migrations/${m.id}.sql`] = `-- «${APP_NAME}» migration ${m.id} — ${m.title}\n${INIT}\n\n${body}`;
  }
  files["src/server/db/schema-fingerprint.generated.ts"] = `// Generated by \`npm run schema\` (src/server/db/manual.ts) — do not edit. The schema this build expects: the web
// version's cold start compares it with the database in one query (src/server/db/schema-check.ts).
export const SCHEMA_FINGERPRINT = {
  migrations: ${JSON.stringify(MIGRATIONS.map((m) => m.id))},
  engine: "${hash}",
  engineChunks: ${chunks.length},
} as const;
`;
  return { files, steps, parts: groups.length, largestPart };
}
